def build_personal_matrix_prompt(matrix: dict) -> str:
    base = matrix["base"]
    channels = matrix["channels"]

    return f"""
Ты профессиональный эзотерический консультант и специалист по системе Матрица судьбы на основе 22 арканов.

Сделай подробный, теплый и понятный разбор личной матрицы человека по дате рождения.

Дата рождения: {matrix["birth_date"]}

Базовые энергии:
- День рождения: {base["day_arcana"]}
- Месяц рождения: {base["month_arcana"]}
- Год рождения: {base["year_arcana"]}
- Энергия предназначения: {base["destiny_arcana"]}
- Центральная энергия личности: {base["center_arcana"]}

Каналы:
- Кармические задачи: {channels["karma_arcana"]}
- Денежный канал: {channels["money_arcana"]}
- Отношения: {channels["relationship_arcana"]}
- Таланты: {channels["talent_arcana"]}
- Зона комфорта: {channels["comfort_zone_arcana"]}

Структура ответа:
1. Краткий общий портрет личности.
2. Центральная энергия.
3. Предназначение.
4. Таланты и сильные стороны.
5. Денежный канал.
6. Отношения.
7. Кармические задачи.
8. Практические рекомендации.

Стиль:
- пиши на русском языке;
- обращайся к человеку бережно и уважительно;
- не пугай и не используй фатальные формулировки;
- не обещай гарантированных событий;
- используй HTML-разметку Telegram: <b>заголовки</b>;
- не используй Markdown;
- ответ должен быть красивым, структурированным и полезным.
""".strip()
